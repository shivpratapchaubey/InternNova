// Arithmetic operator
let a = 10;
let b = 5;

console.log(a + b);
console.log(a - b);
console.log(a * b);
console.log(a / b);
console.log(a % b);
// Assignment operator
let x = 10;

x += 5;
console.log(x);

x -= 2;
console.log(x);

x *= 2;
console.log(x);
// comparision operator
let p = 10;
let q = 20;

console.log(p > q);
console.log(p < q);
console.log(p == q);
console.log(p != q);
console.log(p === q);
// Logical operator
let age = 20;
let hasID = true;

console.log(age >= 18 && hasID);
console.log(age >= 18 || hasID);
console.log(!hasID);
// increment operator
let count = 1;

count++;
console.log(count);
// decrement
count--;
console.log(count);